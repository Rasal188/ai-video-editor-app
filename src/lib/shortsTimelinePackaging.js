/**
 * Exports the canonical timeline to standard OpenTimelineIO (OTIO v1.0) JSON.
 * Formats tracks into OTIO Stack containing Video and Audio tracks with Clips, Gaps,
 * and ExternalReferences.
 *
 * @param {object} timeline - Canonical timeline object
 * @param {object} options - Frame rate and formatting options
 * @returns {object} OTIO Timeline schema JSON object
 */
export function exportTimelineToOtio(timeline = {}, options = {}) {
  if (!timeline || typeof timeline !== "object") {
    throw new Error("Invalid timeline: timeline object is required");
  }

  const rate = Number(options.frameRate || timeline.frameRate || 30);
  const duration = Number(timeline.duration) || 15;

  const otioTracks = [];

  // Helper: map media ID to target URL
  const resolveTargetUrl = (mediaId) => {
    const media = timeline.mediaManifest?.find((m) => m.id === mediaId);
    return media?.path || media?.src || `media/${mediaId}.mp4`;
  };

  // 1. Video Tracks (V2 B-Roll on top, V1 Primary below)
  const v2Track = timeline.tracks?.find((t) => t.id === CANONICAL_TRACK_IDS.V2_BROLL);
  if (v2Track && v2Track.clips?.length > 0) {
    const v2Children = [];
    let cursor = 0;

    v2Track.clips.forEach((clip) => {
      if (clip.timelineStart > cursor) {
        // Gap before this B-roll clip
        v2Children.push({
          OTIO_SCHEMA: "Gap.1",
          metadata: {},
          name: "V2 Gap",
          source_range: toTimeRange(0, clip.timelineStart - cursor, rate),
        });
      }

      v2Children.push({
        OTIO_SCHEMA: "Clip.1",
        name: clip.name,
        metadata: {
          ai_shorts_studio: {
            kind: clip.kind,
            relevanceScore: clip.meta?.relevanceScore,
            transitionIn: clip.transitionIn,
          },
        },
        source_range: toTimeRange(clip.sourceStart, clip.duration, rate),
        media_reference: {
          OTIO_SCHEMA: "ExternalReference.1",
          metadata: {},
          name: clip.name,
          target_url: resolveTargetUrl(clip.mediaId),
          available_range: null,
        },
      });

      cursor = clip.timelineStart + clip.duration;
    });

    if (cursor < duration) {
      v2Children.push({
        OTIO_SCHEMA: "Gap.1",
        metadata: {},
        name: "V2 End Gap",
        source_range: toTimeRange(0, duration - cursor, rate),
      });
    }

    otioTracks.push({
      OTIO_SCHEMA: "Track.1",
      metadata: {},
      name: "V2 - B-Roll & Visual Overlays",
      kind: "Video",
      children: v2Children,
    });
  }

  // V1 Primary Track
  const v1Track = timeline.tracks?.find((t) => t.id === CANONICAL_TRACK_IDS.V1_PRIMARY);
  if (v1Track?.clips?.[0]) {
    const v1 = v1Track.clips[0];
    const v1Children = [
      {
        OTIO_SCHEMA: "Clip.1",
        name: v1.name,
        metadata: {
          ai_shorts_studio: {
            framingMode: v1.framingMode,
            cropX: v1.cropX,
            punchIns: v1.punchIns,
          },
        },
        source_range: toTimeRange(v1.sourceStart, v1.duration, rate),
        media_reference: {
          OTIO_SCHEMA: "ExternalReference.1",
          metadata: {},
          name: v1.name,
          target_url: resolveTargetUrl(v1.mediaId),
          available_range: null,
        },
      },
    ];

    otioTracks.push({
      OTIO_SCHEMA: "Track.1",
      metadata: {},
      name: "V1 - Primary Video",
      kind: "Video",
      children: v1Children,
    });
  }

  // 2. Audio Tracks (A1 Voice, A2 Music)
  const a1Track = timeline.tracks?.find((t) => t.id === CANONICAL_TRACK_IDS.A1_VOICE);
  if (a1Track?.clips?.[0]) {
    const a1 = a1Track.clips[0];
    otioTracks.push({
      OTIO_SCHEMA: "Track.1",
      metadata: {},
      name: "A1 - Dialogue & Speech Audio",
      kind: "Audio",
      children: [
        {
          OTIO_SCHEMA: "Clip.1",
          name: a1.name,
          metadata: {},
          source_range: toTimeRange(a1.sourceStart, a1.duration, rate),
          media_reference: {
            OTIO_SCHEMA: "ExternalReference.1",
            metadata: {},
            name: a1.name,
            target_url: resolveTargetUrl(a1.mediaId),
            available_range: null,
          },
        },
      ],
    });
  }

  const a2Track = timeline.tracks?.find((t) => t.id === CANONICAL_TRACK_IDS.A2_MUSIC);
  if (a2Track?.clips?.length > 0) {
    const a2Children = a2Track.clips.map((m) => ({
      OTIO_SCHEMA: "Clip.1",
      name: m.name,
      metadata: {
        ai_shorts_studio: {
          ducking: m.ducking,
          volume: m.volume,
        },
      },
      source_range: toTimeRange(m.sourceStart, m.duration, rate),
      media_reference: {
        OTIO_SCHEMA: "ExternalReference.1",
        metadata: {},
        name: m.name,
        target_url: resolveTargetUrl(m.mediaId),
        available_range: null,
      },
    }));

    otioTracks.push({
      OTIO_SCHEMA: "Track.1",
      metadata: {},
      name: "A2 - Background Music",
      kind: "Audio",
      children: a2Children,
    });
  }

  // Package Subtitles and Motion Typography into OTIO Timeline Metadata
  const subTrack = timeline.tracks?.find((t) => t.id === CANONICAL_TRACK_IDS.SUBTITLES);
  const captionsMetadata = subTrack?.clips || [];

  return {
    OTIO_SCHEMA: "Timeline.1",
    metadata: {
      ai_shorts_studio: {
        title: timeline.title,
        aspectRatio: timeline.aspectRatio,
        resolution: timeline.resolution,
        markers: timeline.markers || [],
        captions: captionsMetadata,
        transitions: timeline.transitions || [],
      },
    },
    name: timeline.title || "AI Short",
    global_start_time: toRationalTime(0, rate),
    tracks: {
      OTIO_SCHEMA: "Stack.1",
      metadata: {},
      name: "tracks",
      children: otioTracks,
    },
  };
}

/**
 * Deserializes an OpenTimelineIO (OTIO v1.0) JSON structure back into the canonical timeline model.
 *
 * @param {object} otioJson - OTIO timeline JSON object
 * @returns {object} Canonical timeline object
 */
export function deserializeOtioToTimeline(otioJson = {}) {
  if (!otioJson || otioJson.OTIO_SCHEMA !== "Timeline.1") {
    throw new Error("Invalid OTIO payload: missing OTIO_SCHEMA: Timeline.1");
  }

  const title = otioJson.name || "OTIO Short";
  const meta = otioJson.metadata?.ai_shorts_studio || {};
  const targetRatio = normalizeTargetRatio(meta.aspectRatio || "9:16");
  const ratioDef = getRepackagingRatioDefinition(targetRatio);

  const otioTracks = otioJson.tracks?.children || [];
  const rate = otioTracks[0]?.children?.[0]?.source_range?.duration?.rate || 30;

  // Extract V1 and V2 tracks
  const v1Otio = otioTracks.find((t) => t.kind === "Video" && t.name.includes("V1"));
  const v2Otio = otioTracks.find((t) => t.kind === "Video" && t.name.includes("V2"));
  const a1Otio = otioTracks.find((t) => t.kind === "Audio" && t.name.includes("A1"));

  let duration = 15;
  const v1Clips = [];

  if (v1Otio?.children?.[0]) {
    const c = v1Otio.children[0];
    const durSec = Number(c.source_range?.duration?.value || 0) / rate;
    const startSec = Number(c.source_range?.start_time?.value || 0) / rate;
    duration = durSec;

    v1Clips.push({
      id: "clip-v1",
      trackId: CANONICAL_TRACK_IDS.V1_PRIMARY,
      name: c.name,
      mediaId: "src-primary",
      timelineStart: 0,
      duration: durSec,
      sourceStart: startSec,
      sourceDuration: durSec,
      type: "video",
      fitMode: "cover",
      cropX: c.metadata?.ai_shorts_studio?.cropX ?? 0.5,
      punchIns: c.metadata?.ai_shorts_studio?.punchIns || [],
    });
  }

  // Reconstitute V2 B-roll clips from OTIO
  const v2Clips = [];
  if (v2Otio?.children) {
    let timelineCursor = 0;
    v2Otio.children.forEach((item, idx) => {
      const itemDur = Number(item.source_range?.duration?.value || 0) / rate;
      if (item.OTIO_SCHEMA === "Clip.1") {
        const itemSrcStart = Number(item.source_range?.start_time?.value || 0) / rate;
        v2Clips.push({
          id: `ov-otio-${idx + 1}`,
          trackId: CANONICAL_TRACK_IDS.V2_BROLL,
          name: item.name,
          mediaId: `asset-otio-${idx + 1}`,
          timelineStart: timelineCursor,
          duration: itemDur,
          sourceStart: itemSrcStart,
          sourceDuration: itemDur,
          type: "image",
          kind: item.metadata?.ai_shorts_studio?.kind || "broll",
          fitMode: "cover",
          transitionIn: item.metadata?.ai_shorts_studio?.transitionIn || "fade",
          meta: {
            relevanceScore: item.metadata?.ai_shorts_studio?.relevanceScore,
          },
        });
      }
      timelineCursor += itemDur;
    });
  }

  // Reconstitute captions from OTIO metadata
  const captionClips = Array.isArray(meta.captions) ? meta.captions : [];

  const tracks = [
    {
      id: CANONICAL_TRACK_IDS.V2_BROLL,
      order: 1,
      name: "V2 - B-Roll & Visual Overlays",
      kind: CANONICAL_TRACK_KINDS.VIDEO,
      clips: v2Clips,
    },
    {
      id: CANONICAL_TRACK_IDS.V1_PRIMARY,
      order: 2,
      name: "V1 - Primary Video Footage",
      kind: CANONICAL_TRACK_KINDS.VIDEO,
      clips: v1Clips,
    },
    {
      id: CANONICAL_TRACK_IDS.SUBTITLES,
      order: 3,
      name: "Subtitles & Motion Typography",
      kind: CANONICAL_TRACK_KINDS.CAPTION,
      clips: captionClips,
    },
  ];

  return {
    id: `timeline-otio-${title.toLowerCase().replace(/[^a-z0-9]/g, "-")}`,
    title,
    duration,
    aspectRatio: targetRatio,
    resolution: { width: ratioDef.width, height: ratioDef.height },
    frameRate: rate,
    tracks,
    transitions: meta.transitions || [],
    markers: meta.markers || [],
    diagnostics: { missingMedia: [], unsupportedFields: [], warnings: [] },
  };
}

/**
 * Exports the canonical timeline to standard FCPXML (Final Cut Pro XML v1.10).
 * Generates clean XML with resources, sequence, spine, connected B-roll clips,
 * audio stems, and titles.
 *
 * @param {object} timeline - Canonical timeline object
 * @param {object} options - Framing and format options
 * @returns {string} XML string
 */
export function exportTimelineToFcpxml(timeline = {}, options = {}) {
  if (!timeline || typeof timeline !== "object") {
    throw new Error("Invalid timeline: timeline object is required");
  }

  const rate = Number(options.frameRate || timeline.frameRate || 30);
  const duration = Number(timeline.duration) || 15;
  const targetRatio = timeline.aspectRatio || "9:16";
  const res = timeline.resolution || { width: 1080, height: 1920 };

  const durationStr = toFcpxmlTime(duration, rate);
  const v1Track = timeline.tracks?.find((t) => t.id === CANONICAL_TRACK_IDS.V1_PRIMARY);
  const v2Track = timeline.tracks?.find((t) => t.id === CANONICAL_TRACK_IDS.V2_BROLL);
  const subTrack = timeline.tracks?.find((t) => t.id === CANONICAL_TRACK_IDS.SUBTITLES);
  const a1Track = timeline.tracks?.find((t) => t.id === CANONICAL_TRACK_IDS.A1_VOICE);

  const v1Clip = v1Track?.clips?.[0];

  let resourcesXml = `    <format id="r1" name="FFVideoFormat${res.width}x${res.height}p${rate}" frameDuration="100/${rate * 100}s" width="${res.width}" height="${res.height}"/>\n`;

  // Register assets in resources
  (timeline.mediaManifest || []).forEach((m, idx) => {
    const resId = `r_asset_${idx + 1}`;
    const srcPath = m.path || m.src || `media/${m.name}`;
    resourcesXml += `    <asset id="${resId}" name="${escapeXml(m.name)}" src="${escapeXml(srcPath)}" duration="${toFcpxmlTime(m.duration, rate)}" hasVideo="${m.type !== "audio" ? 1 : 0}" hasAudio="${m.type !== "image" ? 1 : 0}"/>\n`;
  });

  // Build connected B-roll clips (lane="1")
  let connectedBrollXml = "";
  (v2Track?.clips || []).forEach((broll, idx) => {
    const brollOffset = toFcpxmlTime(broll.timelineStart, rate);
    const brollDur = toFcpxmlTime(broll.duration, rate);
    const brollStart = toFcpxmlTime(broll.sourceStart, rate);
    connectedBrollXml += `              <clip name="${escapeXml(broll.name)}" lane="1" offset="${brollOffset}" duration="${brollDur}" start="${brollStart}">\n`;
    connectedBrollXml += `                <adjust-transform position="${((broll.cropX - 0.5) * 100).toFixed(1)} 0" scale="1 1"/>\n`;
    connectedBrollXml += `              </clip>\n`;
  });

  // Build titles / subtitles (lane="2")
  let connectedTitlesXml = "";
  (subTrack?.clips || []).forEach((cap, idx) => {
    const capOffset = toFcpxmlTime(cap.start, rate);
    const capDur = toFcpxmlTime(cap.duration, rate);
    connectedTitlesXml += `              <title name="${escapeXml(cap.text)}" lane="2" offset="${capOffset}" duration="${capDur}">\n`;
    connectedTitlesXml += `                <text><text-style font="${escapeXml(cap.fontId || "Helvetica")}" fontSize="${cap.captionSize || 22}">${escapeXml(cap.text)}</text-style></text>\n`;
    connectedTitlesXml += `              </title>\n`;
  });

  const v1Start = v1Clip ? toFcpxmlTime(v1Clip.sourceStart, rate) : "0s";
  const v1Dur = v1Clip ? toFcpxmlTime(v1Clip.duration, rate) : durationStr;

  return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE fcpxml>
<fcpxml version="1.10">
  <resources>
${resourcesXml}  </resources>
  <library>
    <event name="AI Shorts Studio">
      <project name="${escapeXml(timeline.title)}">
        <sequence format="r1" duration="${durationStr}">
          <spine>
            <clip name="${escapeXml(v1Clip?.name || "Primary Video")}" offset="0s" duration="${v1Dur}" start="${v1Start}">
              <adjust-transform position="${(((v1Clip?.cropX ?? 0.5) - 0.5) * 100).toFixed(1)} 0" scale="1 1"/>
${connectedBrollXml}${connectedTitlesXml}            </clip>
          </spine>
        </sequence>
      </project>
    </event>
  </library>
</fcpxml>
`;
}

function escapeXml(unsafe = "") {
  return String(unsafe)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&apos;");
}

/**
 * Packages an editable timeline with native project serialization, OTIO JSON,
 * FCPXML, media manifest, and human-readable track summary.
 *
 * @param {object} sourceClip - Source video asset or clip metadata
 * @param {object} candidate - Candidate short from AI Shorts Studio
 * @param {object} options - Aspect ratio, reframing, and transition options
 * @returns {object} High-level timeline export package
 */
export function packageEditableShortTimeline(sourceClip = {}, candidate = {}, options = {}) {
  // 1. Build canonical timeline model
  const timeline = candidateToCanonicalTimeline(sourceClip, candidate, options);

  // 2. Native Project Serialization
  const nativeProject = serializeTimelineToNativeProject(timeline);

  // 3. OpenTimelineIO (OTIO v1.0) JSON
  const otio = exportTimelineToOtio(timeline, options);

  // 4. Final Cut Pro XML (FCPXML v1.10)
  const fcpxml = exportTimelineToFcpxml(timeline, options);

  // 5. Human-readable track and clip summary
  const trackSummary = timeline.tracks.map((t) => ({
    name: t.name,
    kind: t.kind,
    clipCount: t.clips?.length || 0,
    clips: (t.clips || []).map((c) => ({
      name: c.name,
      timelineStart: c.timelineStart ?? c.start ?? 0,
      duration: c.duration,
      mediaId: c.mediaId,
    })),
  }));

  return {
    format: TIMELINE_PACKAGE_FORMAT,
    version: TIMELINE_PACKAGE_VERSION,
    candidateId: candidate.id,
    title: candidate.title,
    duration: timeline.duration,
    aspectRatio: timeline.aspectRatio,
    resolution: timeline.resolution,
    timeline,
    nativeProject,
    otio,
    fcpxml,
    trackSummary,
    mediaManifest: timeline.mediaManifest,
    diagnostics: timeline.diagnostics,
    exportMetadata: timeline.exportMetadata,
  };
}

